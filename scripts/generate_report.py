#!/usr/bin/env python3
"""
AIEval360 — Report Generator

Reads JSON evidence files from evaluation_runs/ and safety_reports/ and
generates a Markdown summary report in reports/.

Usage:
    python scripts/generate_report.py \
        --run-dir evidence/evaluation_runs \
        --safety-dir evidence/safety_reports \
        --output reports/generated_report.md \
        [--title "My Report"]
"""

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path


def load_json_dir(directory: Path) -> list[dict]:
    results = []
    if not directory.exists():
        return results
    for path in sorted(directory.glob("*.json")):
        try:
            results.append(json.loads(path.read_text()))
        except Exception as e:
            print(f"  WARNING: Could not read {path.name}: {e}", file=sys.stderr)
    return results


def status_icon(status: str) -> str:
    return {"PASS": "✅", "WARN": "⚠️", "FAIL": "❌"}.get(status.upper(), "ℹ️")


def gate_icon(passed: bool | None) -> str:
    if passed is True:
        return "✅ PASS"
    if passed is False:
        return "❌ FAIL"
    return "⏳ N/A"


def generate_report(
    run_records: list[dict],
    safety_records: list[dict],
    title: str,
) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        f"# {title}",
        f"",
        f"**Generated:** {now}  ",
        f"**Platform:** AIEval360 v1.0.0  ",
        f"",
        f"---",
        f"",
    ]

    # --- Metric Evaluation Results ---
    lines.append("## Metric Evaluation Results\n")
    if run_records:
        lines.append("| Run ID | Sector | Records | Accuracy | F1 | Status |")
        lines.append("|--------|--------|---------|----------|----|--------|")
        for rec in run_records:
            agg = rec.get("aggregate_metrics", {})
            acc = agg.get("accuracy", {})
            f1 = agg.get("f1", {})
            acc_val = acc.get("value", "—")
            acc_status = acc.get("status", "—")
            f1_val = f1.get("value", "—")
            sector = rec.get("sector", "—")
            n = rec.get("records_evaluated", "—")
            run_id = rec.get("run_id", "—")
            icon = status_icon(acc_status)
            lines.append(f"| `{run_id[-20:]}` | {sector} | {n} | {acc_val} {icon} | {f1_val} | {acc_status} |")
    else:
        lines.append("*No metric evaluation runs found.*\n")

    lines.append("")
    lines.append("---\n")

    # --- Safety Evaluation Results ---
    lines.append("## Safety Evaluation Results\n")
    if safety_records:
        lines.append("| Report ID | Sector | Probes | Passed | Failed | Critical | Gate |")
        lines.append("|-----------|--------|--------|--------|--------|----------|------|")
        for rec in safety_records:
            report_id = rec.get("report_id", "—")
            sector = rec.get("sector", "—")
            total = rec.get("total_probes", "—")
            summary = rec.get("summary", {})
            passed = summary.get("passed", "—")
            failed = summary.get("failed", "—")
            critical = summary.get("critical_failures", "—")
            gate = gate_icon(rec.get("mandatory_gate_passed"))
            lines.append(f"| `{report_id[-20:]}` | {sector} | {total} | {passed} | {failed} | {critical} | {gate} |")
    else:
        lines.append("*No safety evaluation reports found.*\n")

    lines.append("")
    lines.append("---\n")

    # --- Governance Flags ---
    lines.append("## Governance Flags\n")
    any_flags = False
    for rec in run_records:
        flags = rec.get("governance_flags", [])
        for flag in flags:
            any_flags = True
            lines.append(f"- **[{rec.get('sector', '—').upper()}]** {flag.get('flag', '')}: {flag.get('recommendation', flag.get('note', ''))}")
    for rec in safety_records:
        gate_passed = rec.get("mandatory_gate_passed")
        if gate_passed is False:
            any_flags = True
            lines.append(f"- **[{rec.get('sector', '—').upper()}] MANDATORY GATE FAILED** — {rec.get('mandatory_gate_detail', {}).get('note', 'Critical failure detected.')}")
    if not any_flags:
        lines.append("*No governance flags raised.*")

    lines.append("")
    lines.append("---\n")
    lines.append("*Report generated by AIEval360 generate_report.py*")

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="AIEval360 report generator")
    parser.add_argument("--run-dir", default="evidence/evaluation_runs")
    parser.add_argument("--safety-dir", default="evidence/safety_reports")
    parser.add_argument("--output", default="reports/generated_report.md")
    parser.add_argument("--title", default="AIEval360 — Consolidated Evaluation Report")
    args = parser.parse_args()

    run_dir = Path(args.run_dir)
    safety_dir = Path(args.safety_dir)
    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    print(f"Loading evaluation runs from: {run_dir}")
    runs = load_json_dir(run_dir)
    print(f"  Found {len(runs)} run(s).")

    print(f"Loading safety reports from: {safety_dir}")
    safety = load_json_dir(safety_dir)
    print(f"  Found {len(safety)} safety report(s).")

    report_md = generate_report(runs, safety, args.title)
    output_path.write_text(report_md, encoding="utf-8")
    print(f"\n✅ Report written to: {output_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
